-- Практическая работа №2: схема PostgreSQL
-- Применять к новой базе данных. Ограничения с DEFERRABLE позволяют
-- создавать подразделение и назначать его руководителя в одной транзакции.

BEGIN;

CREATE TABLE department_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE employee_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE rooms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

-- head_employee_id ссылается на employees, таблица сотрудников создаётся ниже.
CREATE TABLE departments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(200) NOT NULL,
    type_id           BIGINT NOT NULL REFERENCES department_types(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    parent_id         BIGINT REFERENCES departments(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    head_employee_id  BIGINT NOT NULL,
    CONSTRAINT departments_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT departments_id_head_unique UNIQUE (id, head_employee_id)
);

CREATE TABLE employees (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(250) NOT NULL,
    type_id          BIGINT NOT NULL REFERENCES employee_types(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    department_id    BIGINT NOT NULL REFERENCES departments(id) ON UPDATE RESTRICT ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    manager_id       BIGINT REFERENCES employees(id) ON UPDATE RESTRICT ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    office_room_id   BIGINT REFERENCES rooms(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    is_root_manager  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT employees_not_self_manager CHECK (manager_id IS NULL OR manager_id <> id),
    CONSTRAINT employees_root_manager_rule CHECK (
        (is_root_manager = TRUE AND manager_id IS NULL)
        OR (is_root_manager = FALSE AND manager_id IS NOT NULL)
    ),
    CONSTRAINT employees_id_department_unique UNIQUE (id, department_id)
);

-- Единственный сотрудник может быть корневым руководителем организации.
CREATE UNIQUE INDEX one_root_manager_only
    ON employees (is_root_manager)
    WHERE is_root_manager = TRUE;

-- Руководитель подразделения обязан быть сотрудником именно этого подразделения.
-- Оба FK отложены до COMMIT, чтобы создать подразделение и руководителя одной транзакцией.
ALTER TABLE departments
    ADD CONSTRAINT departments_head_employee_fk
    FOREIGN KEY (head_employee_id)
    REFERENCES employees(id)
    DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE departments
    ADD CONSTRAINT departments_head_must_belong_to_department_fk
    FOREIGN KEY (head_employee_id, id)
    REFERENCES employees(id, department_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE employee_room_access (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON UPDATE RESTRICT ON DELETE CASCADE,
    room_id     BIGINT NOT NULL REFERENCES rooms(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    PRIMARY KEY (employee_id, room_id)
);

-- Если назначен рабочий кабинет, соответствующий доступ должен существовать.
-- Ограничение отложено, чтобы назначить кабинет и доступ в одной транзакции.
ALTER TABLE employees
    ADD CONSTRAINT employee_office_requires_room_access_fk
    FOREIGN KEY (id, office_room_id)
    REFERENCES employee_room_access(employee_id, room_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE work_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    started_at  TIMESTAMPTZ NOT NULL,
    ended_at    TIMESTAMPTZ,
    CONSTRAINT work_session_end_after_start CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- Один сотрудник не может иметь более одной незавершённой рабочей сессии.
CREATE UNIQUE INDEX one_open_work_session_per_employee
    ON work_sessions (employee_id)
    WHERE ended_at IS NULL;

CREATE INDEX employees_department_idx ON employees(department_id);
CREATE INDEX employees_manager_idx ON employees(manager_id);
CREATE INDEX departments_parent_idx ON departments(parent_id);
CREATE INDEX work_sessions_employee_started_idx ON work_sessions(employee_id, started_at);

COMMIT;
